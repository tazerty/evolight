/// Evora (EVORA-REV-113) : la chaîne par point de la référence (evora1.py:223, 235, 273-281), refaite
/// à la main avec les fonctions du moteur, pour un jeu de réglages et un espace de sortie : pont
/// aller, gain d'exposition, table de tons bornée au blanc, échelle de chroma, retour de gamme, borne
/// finale, puis mise en gamme du moteur. Comme la référence, elle garde la source du point à côté de
/// sa couleur de scène (le noyau, lui, la retrouve par le pont).
struct ByHand {
    bridge: Bridge,
    table: ToneMap,
    gain: f32,
    to_out: [[f32; 3]; 3],
    from_out: [[f32; 3]; 3],
    luma: [f32; 3],
    /// Evora (EVORA-REV-114) : la marge du retour de gamme ([`MARGIN`] dans le rendu ; nulle, c'est la
    /// loi d'EVORA-REV-113, que lisent les témoins).
    margin: f32,
}

impl ByHand {
    /// La chaîne sous `settings` (exposition en EV, contraste, blancs, noirs), vers `space`.
    fn new(settings: (f64, f64, f64, f64), space: OutputSpace) -> ByHand {
        let (exposure, contrast, whites, blacks) = settings;
        let bridge = Bridge::default();
        ByHand {
            table: crate::evora1::tone::table(&bridge, contrast, whites, blacks),
            bridge,
            gain: (exposure as f32).exp2(),
            to_out: space.from_working(),
            from_out: space.rgb_space().to_space(&REC2020).to_f32(),
            luma: space.luma(),
            margin: MARGIN,
        }
    }

    /// Le rendu du point `source` (Rec.2020 linéaire, lumière d'affichage) dans l'espace de sortie
    /// linéaire, après la mise en gamme du moteur ; `with_return` et `with_bound` posent ou retirent
    /// le retour de gamme et la borne finale.
    fn point(&self, source: [f32; 3], with_return: bool, with_bound: bool) -> [f32; 3] {
        let (mut d, o) = self.displayed(source);
        if with_return {
            d = gamut_return(d, source, &self.to_out, &self.from_out, self.luma, KEPT, self.margin);
        }
        if with_bound {
            let mx = d[0].max(d[1]).max(d[2]);
            if mx > DISPLAY_WHITE {
                let t = ((mx - DISPLAY_WHITE) / (mx - o).max(BOUND_FLOOR)).clamp(0.0, 1.0);
                d = d.map(|v| v + (o - v) * t);
            }
        }
        gamut_map(mul3(&self.to_out, d), self.luma).0
    }

    /// La couleur d'affichage du point `source` après les tons et l'échelle de chroma, avant le retour
    /// de gamme, et sa luminance d'affichage bornée au blanc.
    fn displayed(&self, source: [f32; 3]) -> ([f32; 3], f32) {
        let c = self.bridge.scene_of(source).map(|v| v * self.gain);
        let yl = luminance_2020(c);
        let o = self.table.apply(yl).min(DISPLAY_WHITE);
        let shown = if yl > SCENE_FLOOR { c.map(|v| v * o / yl) } else { [0.0; 3] };
        let k = self.table.chroma_scale(o);
        (shown.map(|v| o + (v - o) * k), o)
    }

    /// Evora (EVORA-REV-114) : l'excès relatif du point `source` sur la référence de son retour de
    /// gamme, sa source retrouvée par le pont depuis sa couleur de scène, comme le noyau la retrouve
    /// (`Kernel::gamut_return`) ; positif, le retour de gamme s'éveille. C'est la chaîne refaite à la
    /// main sur ce poste, non le moteur : un diagnostic, que les tests ne jugent pas.
    fn excess_by_the_bridge(&self, source: [f32; 3]) -> f32 {
        let (d, _) = self.displayed(source);
        let found = self.bridge.source_of(self.bridge.scene_of(source));
        let reference = reference_of(found, &self.to_out);
        (peak_of(d, &self.to_out) - reference) / reference
    }
}

/// Le plus grand écart entre deux couleurs, canal par canal. Un écart qui n'est pas un nombre est le
/// pire des écarts.
fn gap_of(a: [f32; 3], b: [f32; 3]) -> f64 {
    let mut worst = 0.0f64;
    for c in 0..3 {
        let gap = (f64::from(a[c]) - f64::from(b[c])).abs();
        worst = if gap.is_nan() { f64::INFINITY } else { worst.max(gap) };
    }
    worst
}

/// Un espace de sortie du test de la chaîne : ses vecteurs, sa tolérance, et si la borne finale y
/// travaille sur ces vecteurs.
struct PushedChain {
    space: OutputSpace,
    vectors: &'static [ChainVector],
    tol: f64,
    bound_at_work: bool,
}

/// Evora (EVORA-REV-113) : exposition, contraste, blancs et noirs, rendus sous `Evora1` par le rendu
/// entier, face aux vecteurs d'or de la chaîne par point de la référence, sur les jeux de réglages
/// où son retour de gamme ramène au moins une des dix couleurs, dans trois espaces de sortie : sRGB,
/// P3 et l'espace de travail. La sortie est lue en flottants linéaires dans l'espace de sortie ;
/// l'attendu est le rendu de la référence mené dans cet espace, puis mis en gamme par le moteur.
/// Dans l'espace de travail, la borne finale travaille sur douze de ces vecteurs.
///
/// Sabotages qui le font rougir : le retour de gamme non posé dans le noyau, ou posé après la borne ;
/// la source lue en lumière de scène au lieu d'être retrouvée par le pont ; la matrice de retour d'un
/// autre espace que la sortie ; la part de l'excès rendue en luminance changée. Témoins intégrés, sur
/// la chaîne refaite à la main (qui, entière, rend l'attendu) : sans le retour de gamme, elle manque
/// la tolérance sur au moins `WITNESSES_MIN` vecteurs par espace ; sans la borne finale, elle la
/// manque dans l'espace de travail.
#[test]
fn render_matches_the_reference_through_the_gamut_return() {
    let info = SourceInfo::default();
    let chains = [
        PushedChain { space: OutputSpace::Srgb, vectors: &GOLD_CHAIN_PUSHED_SRGB, tol: PUSHED_CHAIN_TOL, bound_at_work: false },
        PushedChain { space: OutputSpace::DisplayP3, vectors: &GOLD_CHAIN_PUSHED_P3, tol: PUSHED_CHAIN_TOL, bound_at_work: false },
        PushedChain { space: OutputSpace::Rec2020, vectors: &GOLD_CHAIN_PUSHED_REC2020, tol: PUSHED_CHAIN_TOL, bound_at_work: true },
    ];
    for chain in chains {
        let (space, tol) = (chain.space, chain.tol);
        let (to_out, luma) = (space.from_working(), space.luma());
        let (mut start, mut groups, mut without_return, mut without_bound) = (0usize, 0usize, 0usize, 0usize);
        while start < chain.vectors.len() {
            // un jeu de réglages : les vecteurs qui se suivent sous les mêmes quatre curseurs
            let settings = chain.vectors[start].0;
            let group: Vec<&ChainVector> = chain.vectors[start..].iter().take_while(|v| v.0 == settings).collect();
            start += group.len();
            groups += 1;
            let (exposure, contrast, whites, blacks) = settings;
            let src = Rgb32f::from_fn(group.len(), 1, |x, _| group[x].1);
            let req = RenderRequest { depth: OutputDepth::F32Linear, space, ..RenderRequest::fit(group.len(), 1) };
            let got = float_points(render(&src, &info, &toned(Process::Evora1, exposure, (contrast, whites, blacks)), &req));
            assert_eq!(got.len(), group.len(), "{space:?}, réglages {settings:?} : un point de rendu par vecteur");

            let hand = ByHand::new(settings, space);
            for (i, (out, vector)) in got.iter().zip(&group).enumerate() {
                let source = vector.1;
                // l'attendu : le rendu de la référence, mené dans l'espace de sortie, mis en gamme par le moteur
                let want = gamut_map(mul3(&to_out, vector.2.map(|c| c as f32)), luma).0;
                let gap = gap_of(*out, want);
                assert!(
                    gap <= tol,
                    "{space:?}, réglages {settings:?}, source {source:?} (vecteur {i} du jeu) : rendu {out:?}, référence {want:?}, écart {gap}"
                );
                // la chaîne refaite à la main, entière, rend l'attendu : ses variantes sabordées sont des témoins
                let by_hand = gap_of(hand.point(source, true, true), want);
                assert!(
                    by_hand <= tol,
                    "{space:?}, réglages {settings:?}, source {source:?} : la chaîne refaite à la main manque la référence de {by_hand}"
                );
                if gap_of(hand.point(source, false, true), want) > tol {
                    without_return += 1;
                }
                if gap_of(hand.point(source, true, false), want) > tol {
                    without_bound += 1;
                }
            }
        }
        assert!(groups >= 2, "garde de portée : {space:?}, {groups} jeu(x) de réglages lu(s)");
        // témoins rouges
        assert!(
            without_return >= WITNESSES_MIN,
            "témoin : {space:?}, sans le retour de gamme, {without_return} vecteur(s) seulement manquent la référence"
        );
        if chain.bound_at_work {
            assert!(without_bound >= 1, "témoin : {space:?}, sans la borne finale, aucun vecteur ne manque la référence");
        }
    }
}

/// La rotation moyenne de la teinte OkLab, en degrés, entre deux rendus du même fichier (sortie
/// linéaire, ramenée au Rec.2020 par `from_out`), sur les points colorés dans les deux, et le nombre
/// de ces points (contrôle « teinte tenue » de la référence).
fn mean_hue_turn(from_out: &[[f32; 3]; 3], before: &[[f32; 3]], after: &[[f32; 3]]) -> (f64, usize) {
    assert_eq!(before.len(), after.len(), "deux rendus du même fichier");
    let lab = |p: [f32; 3]| oklab_from_2020(mul3(from_out, p).map(|v| v.max(0.0))).map(f64::from);
    let (mut sum, mut coloured) = (0.0f64, 0usize);
    for (&a, &b) in before.iter().zip(after) {
        let (a, b) = (lab(a), lab(b));
        if a[1].hypot(a[2]) > CONTROL_COLOURED_CHROMA && b[1].hypot(b[2]) > CONTROL_COLOURED_CHROMA {
            let turn = (b[2].atan2(b[1]) - a[2].atan2(a[1]) + std::f64::consts::PI).rem_euclid(std::f64::consts::TAU) - std::f64::consts::PI;
            sum += turn.abs().to_degrees();
            coloured += 1;
        }
    }
    (if coloured > 0 { sum / coloured as f64 } else { 0.0 }, coloured)
}

/// Evora (EVORA-REV-113) : monter l'exposition ne fait pas tourner la teinte (contrôle « teinte
/// tenue » de la référence, à son exposition). Sur le treillis de 5 832 couleurs sRGB, rendu en sRGB
/// sous `Evora1` aux réglages neutres puis à cette exposition, la rotation moyenne de la teinte OkLab
/// des points colorés reste sous `CONTROL_HUE_MAX` degrés : une couleur vive que l'exposition pousse
/// hors de la gamme y est ramenée par le retour de gamme, qui lui rend sa teinte.
///
/// Sabotages qui le font rougir : le retour de gamme non posé (la mise en gamme du moteur désature
/// seule, en lumière linéaire, et la couleur vire) ; la teinte rendue prise après la désaturation.
/// Témoin intégré : la chaîne refaite à la main sans le retour de gamme passe le seuil.
#[test]
fn pushed_colours_keep_their_hue() {
    let info = SourceInfo::default();
    let file = srgb_lattice();
    let src = decoded(&file);
    let space = OutputSpace::Srgb;
    let from_out = space.rgb_space().to_space(&REC2020).to_f32();
    let req = RenderRequest { depth: OutputDepth::F32Linear, space, ..RenderRequest::fit(file.width, file.height) };
    let rendered = |exposure: f64| float_points(render(&src, &info, &at(Process::Evora1, exposure), &req));
    let (neutral, pushed) = (rendered(0.0), rendered(CONTROL_HUE_EXPOSURE));
    assert_eq!(neutral.len(), src.data.len(), "un point de rendu par point du fichier");

    let (turn, coloured) = mean_hue_turn(&from_out, &neutral, &pushed);
    assert!(2 * coloured > src.data.len(), "garde de portée : {coloured} point(s) coloré(s) seulement sur {}", src.data.len());
    assert!(
        turn <= CONTROL_HUE_MAX,
        "exposition {CONTROL_HUE_EXPOSURE} : la teinte tourne de {turn}° en moyenne sous Evora1, {CONTROL_HUE_MAX}° admis"
    );

    // témoin rouge : sans le retour de gamme, la mise en gamme du moteur fait virer les couleurs poussées
    let hand = ByHand::new((CONTROL_HUE_EXPOSURE, 0.0, 0.0, 0.0), space);
    let without: Vec<[f32; 3]> = src.data.iter().map(|&c| hand.point(c, false, true)).collect();
    let (witness, _) = mean_hue_turn(&from_out, &neutral, &without);
    assert!(witness > CONTROL_HUE_MAX, "témoin : sans le retour de gamme, la teinte ne tourne que de {witness}° en moyenne");
}

/// Evora (EVORA-REV-113) : pour un écran, le retour de gamme se fait dans les primaires de l'écran.
/// Le treillis, rendu sous `Evora1` à l'exposition du contrôle de la teinte, donne en 8 bits pour un
/// écran aux primaires P3 ce que donne le rendu dans l'espace de sortie P3, à `DISPLAY_CODE_TOL` code
/// près (la trame). `FinishParams::for_display` change la matrice de sortie du noyau : la matrice de
/// retour du retour de gamme doit la suivre.
///
/// Sabotage qui le fait rougir : le noyau d'Evora laissé dans l'espace de sortie demandé quand le
/// rendu se fait pour un écran. Témoin intégré : la chaîne refaite à la main avec la matrice de
/// sortie de l'écran et la matrice de retour de sRGB manque le rendu pour l'écran de plus de
/// `WITNESS_CODES` codes sur au moins `WITNESSES_MIN` points.
#[test]
fn display_render_runs_the_gamut_return_in_the_display_space() {
    let info = SourceInfo::default();
    let file = srgb_lattice();
    let src = decoded(&file);
    let s = at(Process::Evora1, CONTROL_HUE_EXPOSURE);
    let wide = OutputSpace::DisplayP3;
    let Some(display) = DisplaySpace::of(wide, 1) else {
        panic!("écran de test refusé");
    };
    let fit = RenderRequest::fit(file.width, file.height);
    let by_space = render(&src, &info, &s, &RenderRequest { space: wide, ..fit }).image;
    let on_display = render(&src, &info, &s, &RenderRequest { display: Some(display), ..fit }).image;
    assert_eq!(on_display.data.len(), src.data.len(), "un point de rendu par point du fichier");
    let mut worst = 0i32;
    for (a, b) in by_space.data.iter().zip(&on_display.data) {
        for c in 0..3 {
            worst = worst.max((i32::from(a[c]) - i32::from(b[c])).abs());
        }
    }
    assert!(worst <= DISPLAY_CODE_TOL, "le rendu pour un écran P3 s'écarte de {worst} code(s) du rendu en P3, {DISPLAY_CODE_TOL} admis");

    // témoin rouge : la matrice de sortie de l'écran, avec la matrice de retour de l'espace demandé
    let settings = (CONTROL_HUE_EXPOSURE, 0.0, 0.0, 0.0);
    let mixed = ByHand { from_out: ByHand::new(settings, OutputSpace::Srgb).from_out, ..ByHand::new(settings, wide) };
    let mut missed = 0usize;
    for (&c, shown) in src.data.iter().zip(&on_display.data) {
        let code = mixed.point(c, true, true).map(|v| f64::from(linear_to_srgb(v.clamp(0.0, 1.0))) * 255.0);
        if (0..3).any(|k| (code[k] - f64::from(shown[k])).abs() > WITNESS_CODES) {
            missed += 1;
        }
    }
    assert!(missed >= WITNESSES_MIN, "témoin : avec la matrice de retour de sRGB, {missed} point(s) seulement manquent le rendu pour l'écran");
}

/// Evora (EVORA-REV-114) : écart admis, en code sRGB sur 255 (flottants, sans trame), entre le rendu
/// neutre sous `Evora1` d'un fichier P3 rendu en sRGB et le rendu de V6 du même fichier, aux points
/// dont la source sort de la gamme sRGB (par le haut ou par le bas) ou dont un canal du fichier touche
/// le blanc ; ailleurs, c'est `NEUTRAL_CODE_TOL`.
///
/// Mesuré hors moteur sur le treillis (émulation du noyau en simple précision) : 0,0053 code ; 0,0104
/// la source décalée d'un dernier chiffre ; 0,0106 et 0,0132 quand les puissances, racines cubiques,
/// hypoténuses et logarithmes bougent d'un ou de deux derniers chiffres (40 tirages chacun, source
/// décalée ou non). Le runner, lui, a mesuré 0,0533 code au run D (43370713268, sous la loi
/// d'EVORA-REV-113) sur des sources dont le plus grand canal sRGB tient sous le blanc, là où
/// l'émulation ne donne que 0,0005 à 0,0010 : l'émulation ne reproduit pas ce que le runner a vu, et
/// la cause de cet écart n'est pas prouvée.
///
/// Ce que l'émulation montre : au blanc, l'écart croît avec l'excès relatif `ε` de la couleur sur sa
/// source, et c'est la mise en gamme finale du moteur qui l'amplifie, non le retour de gamme. Pour un
/// excès commun aux trois canaux, la loi neuve donne 0,013 code à `ε` = 1e-6, 0,032 à 3e-6, 0,108 à
/// 1e-5 ; sans retour de gamme, la mise en gamme finale seule en donne le double (le gain de la loi
/// rend une part de l'excès en luminance). Un jaune P3 au blanc (codes 255, 255, b) poussé de 32
/// derniers chiffres s'écarte de 0,052 code sous la loi d'EVORA-REV-113, l'ordre des 0,0533 du runner,
/// et encore de 0,033 sous la loi neuve : une borne de 0,03 n'y tiendrait pas. La borne vaut un
/// huitième de code, un peu plus du double des 0,0533 du runner ; elle cède vers `ε` = 1,2e-5 (une
/// centaine de derniers chiffres au blanc). Elle reste au quart du seuil d'identité de la référence
/// (`CONTROL_IDENTITY_MAX`), et deux cents fois sous les sauts de la loi d'EVORA-REV-113 (26 à 39
/// codes, que lit le témoin).
const WIDE_NEUTRAL_CODE_TOL: f64 = 0.125;
/// Evora (EVORA-REV-113) : un code sur 8 bits : un point qui s'écarte de plus du rendu de V6 a sauté.
const JUMP_CODE: f64 = 1.0;

/// Le plus grand écart, en codes sRGB sur 8 bits (sans trame), entre deux couleurs de sortie linéaire.
/// Un écart qui n'est pas un nombre est le pire des écarts.
fn code_gap(a: [f32; 3], b: [f32; 3]) -> f64 {
    let code = |v: f32| f64::from(linear_to_srgb(v)) * 255.0;
    let mut worst = 0.0f64;
    for c in 0..3 {
        let gap = (code(a[c]) - code(b[c])).abs();
        worst = if gap.is_nan() { f64::INFINITY } else { worst.max(gap) };
    }
    worst
}

/// Evora (EVORA-REV-114) : aux réglages neutres, un fichier P3 rendu en sRGB rend ce que rend V6 (le
/// fichier mis en gamme par le moteur). Treillis de 5 832 couleurs lu comme un fichier P3, sorti en
/// flottants sRGB linéaires, en deux ensembles :
/// - les sources dans la gamme sRGB par les deux bords, hors des points du fichier dont un canal touche
///   le blanc (2 527 points) : à `NEUTRAL_CODE_TOL` près, la marge de la trame, comme le neutre d'un
///   fichier sRGB (mesuré hors moteur : 0,0005 ; 0,0010 sous perturbation d'un ou de deux derniers
///   chiffres) ;
/// - les autres, sources hors de la gamme sRGB par le haut ou par le bas, ou au blanc : à
///   `WIDE_NEUTRAL_CODE_TOL` près.
///
/// Là où la source sort de la gamme sRGB par le haut, la référence du retour de gamme passe le blanc
/// (la source y a déjà son pic), et le bruit d'arrondi du pont peut faire passer la couleur au-dessus
/// (test strict `mx > ref`, pont.py:93). Sous la loi de la référence du 2026-11-13, la teinte n'y est
/// rendue qu'en proportion de l'excès relatif, divisé par la marge `MARGIN` : l'arrondi y pèse vingt
/// fois, sur l'écart entre la teinte rendue et la couleur désaturée, qui va jusqu'à 39 codes. Ce test
/// lit le rendu du moteur, non ses réveils : combien de points éveillent le retour de gamme dans le
/// moteur, il ne le voit pas. Hors moteur, la chaîne refaite à la main l'éveille sur 475 points, tous
/// hors de la gamme sRGB ; en cas d'échec, le message donne le pire point de la lecture qui échoue, ses
/// codes, l'écart de la chaîne refaite à la main avec et sans retour de gamme, son excès relatif par le
/// pont (comme le noyau retrouve la source), et le compte de ces réveils sur le poste qui joue le test.
///
/// Sabotages qui le font rougir (mesurés hors moteur) : la teinte rendue en plein dès le seuil (la loi
/// d'EVORA-REV-113) ; l'excès jugé contre le blanc au lieu de la référence de la source (par la chaîne
/// refaite à la main : 70 codes, 1 071 couleurs au-delà de `WIDE_NEUTRAL_CODE_TOL`). Témoin intégré :
/// la chaîne refaite à la main sous la
/// loi d'EVORA-REV-113 (marge nulle : l'excès, infini, est borné à 1 dès le seuil) fait sauter de
/// plus de `JUMP_CODE` au moins `WITNESSES_MIN` couleurs.
#[test]
fn neutral_wide_file_keeps_the_engine_gamut_map() {
    let info = SourceInfo::default();
    // le treillis sRGB, ses octets lus comme un fichier P3 (D65)
    let file = srgb_lattice();
    let to_working = OutputSpace::DisplayP3.rgb_space().to_space(&REC2020);
    let src = file.to_linear().map(|c| to_working.apply_f32(c));
    let space = OutputSpace::Srgb;
    let to_out = space.from_working();
    let req = RenderRequest { depth: OutputDepth::F32Linear, space, ..RenderRequest::fit(file.width, file.height) };
    let evora = float_points(render(&src, &info, &at(Process::Evora1, 0.0), &req));
    let v6 = float_points(render(&src, &info, &at(Process::V6, 0.0), &req));
    assert_eq!((evora.len(), v6.len()), (src.data.len(), src.data.len()), "un point de rendu par point du fichier");
    assert!(WIDE_NEUTRAL_CODE_TOL <= CONTROL_IDENTITY_MAX, "tolérance du fichier P3 au-dessus du seuil d'identité de la référence");
    let hand = ByHand::new((0.0, 0.0, 0.0, 0.0), space);
    // témoin : la loi d'EVORA-REV-113, la teinte rendue en plein dès le seuil
    let old_law = ByHand { margin: 0.0, ..ByHand::new((0.0, 0.0, 0.0, 0.0), space) };
    let is_outside = |source: [f32; 3]| mul3(&to_out, source).iter().any(|&v| !(0.0..=DISPLAY_WHITE).contains(&v));

    // (pire écart en code, index du point) : dans la gamme hors du blanc, puis tous les autres points
    let (mut worst_inside, mut worst_edge) = ((0.0f64, 0usize), (0.0f64, 0usize));
    let (mut inside, mut outside, mut woken, mut witness_jumped) = (0usize, 0usize, 0usize, 0usize);
    for (i, ((&source, &got), &plain)) in src.data.iter().zip(&evora).zip(&v6).enumerate() {
        let gap = code_gap(got, plain);
        let source_outside = is_outside(source);
        outside += usize::from(source_outside);
        woken += usize::from(hand.excess_by_the_bridge(source) > 0.0);
        let worst = if source_outside || touches_white(&file.data[i]) {
            &mut worst_edge
        } else {
            inside += 1;
            &mut worst_inside
        };
        if gap > worst.0 {
            *worst = (gap, i);
        }
        if code_gap(old_law.point(source, true, true), plain) > JUMP_CODE {
            witness_jumped += 1;
        }
    }
    // le pire point d'un des deux ensembles, de quoi lire un échec en un seul passage de la CI
    let codes = |v: [f32; 3]| v.map(|x| f64::from(linear_to_srgb(x)) * 255.0);
    let describe = |i: usize| {
        let source = src.data[i];
        format!(
            "point {i}, fichier P3 {:?}, source sRGB linéaire {:?} ({}) : codes rendus {:?}, codes de V6 {:?} ; \
             chaîne refaite à la main : {:.4} code d'écart à V6, {:.4} sans retour de gamme, excès relatif par le pont {:e} ; \
             {woken} point(s) où la chaîne refaite à la main éveille le retour de gamme",
            &file.data[i][..3],
            mul3(&to_out, source),
            if is_outside(source) { "hors de la gamme sRGB" } else { "dans la gamme sRGB" },
            codes(evora[i]),
            codes(v6[i]),
            code_gap(hand.point(source, true, true), v6[i]),
            code_gap(hand.point(source, false, true), v6[i]),
            hand.excess_by_the_bridge(source),
        )
    };
    assert!(
        inside > 0 && outside > 0 && outside < src.data.len(),
        "garde de portée : {inside} source(s) dans la gamme sRGB hors du blanc, {outside} hors de la gamme sRGB, sur {}",
        src.data.len()
    );
    assert!(
        worst_inside.0 <= NEUTRAL_CODE_TOL,
        "sources dans la gamme sRGB, hors du blanc : {} code d'écart au rendu de V6, {NEUTRAL_CODE_TOL} admis ; {}",
        worst_inside.0,
        describe(worst_inside.1)
    );
    assert!(
        worst_edge.0 <= WIDE_NEUTRAL_CODE_TOL,
        "sources hors de la gamme sRGB ou au blanc : {} code d'écart au rendu de V6, {WIDE_NEUTRAL_CODE_TOL} admis ; {}",
        worst_edge.0,
        describe(worst_edge.1)
    );
    // témoin rouge : sous la loi d'EVORA-REV-113, des couleurs hors de la gamme sRGB sautent
    assert!(
        witness_jumped >= WITNESSES_MIN,
        "témoin : sous la loi d'EVORA-REV-113, {witness_jumped} couleur(s) seulement sautent de plus de {JUMP_CODE} code"
    );
}
